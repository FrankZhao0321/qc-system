echo "✅ 前端配置完成！"
echo ""

# 创建数据库 SQL 文件
cat > database-setup.sql << 'EOF'
-- ========================================
-- 奥领数控品控系统 - 数据库初始化
-- ========================================

-- 1. 创建设备表
CREATE TABLE IF NOT EXISTS devices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_number TEXT UNIQUE NOT NULL,
  model TEXT NOT NULL,
  customer TEXT NOT NULL,
  order_number TEXT NOT NULL,
  status TEXT DEFAULT 'assembling',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. 创建组装检测表
CREATE TABLE IF NOT EXISTS assembly_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT REFERENCES devices(id) ON DELETE CASCADE,
  check_item TEXT NOT NULL,
  description TEXT,
  photo_path TEXT,
  inspector TEXT,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. 创建测试报告表
CREATE TABLE IF NOT EXISTS test_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT REFERENCES devices(id) ON DELETE CASCADE,
  test_item TEXT NOT NULL,
  standard TEXT,
  result TEXT,
  tester TEXT,
  test_date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  confirmed BOOLEAN DEFAULT FALSE
);

-- 4. 创建发货清点表
CREATE TABLE IF NOT EXISTS shipping_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT REFERENCES devices(id) ON DELETE CASCADE,
  item_name TEXT NOT NULL,
  item_type TEXT,
  required_quantity INTEGER,
  actual_quantity INTEGER,
  checker TEXT,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. 创建客户反馈表
CREATE TABLE IF NOT EXISTS customer_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT REFERENCES devices(id) ON DELETE CASCADE,
  feedback_type TEXT,
  description TEXT,
  rating INTEGER,
  customer TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. 创建改进建议表
CREATE TABLE IF NOT EXISTS improvement_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT REFERENCES devices(id) ON DELETE CASCADE,
  suggestion TEXT,
  priority TEXT,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ========================================
-- 启用行级安全策略
-- ========================================

ALTER TABLE devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE assembly_checks ENABLE ROW LEVEL SECURITY;
ALTER TABLE test_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE shipping_checks ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE improvement_suggestions ENABLE ROW LEVEL SECURITY;

-- ========================================
-- 创建安全策略（测试阶段 - 允许所有访问）
-- ========================================

DROP POLICY IF EXISTS "Enable all for devices" ON devices;
CREATE POLICY "Enable all for devices" ON devices
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Enable all for assembly_checks" ON assembly_checks;
CREATE POLICY "Enable all for assembly_checks" ON assembly_checks
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Enable all for test_reports" ON test_reports;
CREATE POLICY "Enable all for test_reports" ON test_reports
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Enable all for shipping_checks" ON shipping_checks;
CREATE POLICY "Enable all for shipping_checks" ON shipping_checks
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Enable all for customer_feedback" ON customer_feedback;
CREATE POLICY "Enable all for customer_feedback" ON customer_feedback
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Enable all for improvement_suggestions" ON improvement_suggestions;
CREATE POLICY "Enable all for improvement_suggestions" ON improvement_suggestions
  FOR ALL USING (true) WITH CHECK (true);

-- ========================================
-- 创建索引以提高查询性能
-- ========================================

CREATE INDEX IF NOT EXISTS idx_devices_device_number ON devices(device_number);
CREATE INDEX IF NOT EXISTS idx_devices_status ON devices(status);
CREATE INDEX IF NOT EXISTS idx_assembly_checks_device_id ON assembly_checks(device_id);
CREATE INDEX IF NOT EXISTS idx_test_reports_device_id ON test_reports(device_id);
CREATE INDEX IF NOT EXISTS idx_shipping_checks_device_id ON shipping_checks(device_id);
CREATE INDEX IF NOT EXISTS idx_customer_feedback_device_id ON customer_feedback(device_id);
CREATE INDEX IF NOT EXISTS idx_improvement_suggestions_device_id ON improvement_suggestions(device_id);

-- ========================================
-- 插入测试数据
-- ========================================

-- 设备 1
INSERT INTO devices (device_number, model, customer, order_number, status)
VALUES ('CNC-2024-001', 'XK7132', '华东机械制造有限公司', 'ORDER-2024-001', 'assembling')
ON CONFLICT (device_number) DO NOTHING;

-- 设备 2
INSERT INTO devices (device_number, model, customer, order_number, status)
