ON CONFLICT (device_number) DO NOTHING;

-- 设备 3
INSERT INTO devices (device_number, model, customer, order_number, status)
VALUES ('CNC-2024-003', 'XK7132', '南方汽车零部件公司', 'ORDER-2024-003', 'shipping')
ON CONFLICT (device_number) DO NOTHING;

-- ========================================
-- 完成
-- ========================================

-- 显示创建的表
SELECT 
  table_name,
  (SELECT COUNT(*) FROM information_schema.columns WHERE table_name = t.table_name) as column_count
FROM information_schema.tables t
WHERE t.table_schema = 'public'
  AND t.table_name IN ('devices', 'assembly_checks', 'test_reports', 'shipping_checks', 'customer_feedback', 'improvement_suggestions')
ORDER BY table_name;
EOF

echo "✅ 已创建数据库 SQL 文件：database-setup.sql"
